        public static void Initialize()
        {
            if (_initialized) return;
            _initialized = true;
            string defaultCode = Application.systemLanguage == SystemLanguage.German
                ? "de" : "en";
            CurrentLanguage = Parse(PlayerPrefs.GetString(PrefsKey, defaultCode));
        }

        public static void SetLanguage(AppLanguage language)
        {
            Initialize();
            if (CurrentLanguage == language) return;
            CurrentLanguage = language;
            PlayerPrefs.SetString(PrefsKey, CurrentCode);
            PlayerPrefs.Save();
            LanguageChanged?.Invoke();
        }

        public static void SetLanguage(string code) => SetLanguage(Parse(code));

        public static void ToggleLanguage() => SetLanguage(
            CurrentLanguage == AppLanguage.German
                ? AppLanguage.English : AppLanguage.German);

        public static string Get(string key)
        {
            Initialize();
            Dictionary<string, string> table = CurrentLanguage == AppLanguage.German
                ? De : En;
            if (table.TryGetValue(key, out string value)) return value;
            Dictionary<string, string> fallback = CurrentLanguage == AppLanguage.German
                ? En : De;
            if (fallback.TryGetValue(key, out value)) return value;
            if (MissingKeys.Add(key)) Debug.LogWarning($"[Localization] Missing key: {key}");
            return key;
        }

        public static string Format(string key, params object[] args)
        {
            CultureInfo culture = CurrentLanguage == AppLanguage.German
                ? CultureInfo.GetCultureInfo("de-DE")
                : CultureInfo.GetCultureInfo("en-US");
            return string.Format(culture, Get(key), args);
        }

        /// <summary>Localizes conventional floor labels for display without
        /// changing the labels stored in scans and JSON exports.</summary>
        public static string DisplayFloorLabel(string label)
        {
            Initialize();
            if (CurrentLanguage == AppLanguage.German || string.IsNullOrEmpty(label))
                return label;
            if (label == "EG") return "GF";
            if (label.StartsWith("OG", StringComparison.Ordinal) &&
                int.TryParse(label.Substring(2), out int upper))
                return upper + "F";
            if (label.StartsWith("UG", StringComparison.Ordinal) &&
                int.TryParse(label.Substring(2), out int basement))
                return "B" + basement;
            return label;
        }

        private static AppLanguage Parse(string code) =>
            string.Equals(code, "de", StringComparison.OrdinalIgnoreCase)
                ? AppLanguage.German : AppLanguage.English;
